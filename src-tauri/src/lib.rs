//! The desktop shell.
//!
//! There is deliberately almost nothing here. Every command is one line that
//! hands its arguments to [`notetaker_core::dispatch`], which is the same entry
//! point the HTTP server uses — so the thirty-arm match that decides what a
//! command *means* is written once, tested on Linux, and cannot drift between
//! the desktop app and the served UI.
//!
//! **This crate cannot be compiled on the development machine** (webkit/gtk and
//! `libdbus-sys` need system packages there is no sudo to install), so CI is the
//! only thing that ever type-checks it. That is why the wrappers are written out
//! longhand rather than generated by a macro: boring, repetitive code a reader
//! can check by eye is the right trade when the compiler is not available to the
//! author. Each uses only `#[tauri::command]` with named parameters and `State`,
//! which is the most stable corner of the Tauri API.
//!
//! `rename_all = "camelCase"` is on every command with a multi-word argument.
//! `src/lib/ipc.ts` sends `summaryMd`, `notesMd`, `appId`; the Rust parameters
//! are `summary_md`, `notes_md`, `app_id`. A mismatch is not a compile error and
//! not a visible crash — the invoke simply rejects at runtime and the user reads
//! it as "the button does nothing". `runtime::COMMANDS` is the written-down
//! contract, and a test fails the build if either side drifts from it.


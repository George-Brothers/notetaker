/// Runs one command through core's dispatcher.
///
/// Errors come back as `String` because that is what Tauri sends to the UI. The
/// runtime already writes its failures for someone who is not an engineer, so
/// the message passes through unchanged — `{:#}` keeps the `anyhow` context
/// chain, which is where the useful half of these messages lives.
fn call(rt: &State<'_, Runtime>, command: &str, args: Value) -> Result<Value, String> {
    dispatch(rt.inner(), command, &args).map_err(|e| format!("{e:#}"))
}


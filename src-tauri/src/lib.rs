/// Builds the runtime the whole app hangs off.
///
/// Identical to what `notetaker-serve` does, deliberately: two transports over
/// one runtime, constructed the same way, so a bug cannot be present in one and
/// absent in the other.
fn open_runtime() -> anyhow::Result<Runtime> {
    let storage_root = paths::default_storage_root()?;
    let app_dir = paths::default_app_dir()?;
    log::info!("library: {}", storage_root.display());

    Runtime::open(
        &app_dir,
        &storage_root,
        Box::new(PlatformSources::new()),
        default_probe(),
    )
}

#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    tauri::Builder::default()
        .plugin(tauri_plugin_opener::init())
        .setup(|app| {
            let runtime = open_runtime()?;

            // Recovers what a crash left behind, rebuilds the search index, and
            // starts transcribing in the background. One call, shared with
            // `notetaker-serve`, because this crate never compiles on the
            // development machine — anything written here and nowhere else is
            // unverified until CI.
            runtime.launch();

            app.manage(runtime);
            Ok(())
        })
        .invoke_handler(tauri::generate_handler![
            list_tasks,
            create_task,
            list_recordings,
            get_recording,
            search,
            process_now,
            update_summary,
            assign_task,
            rename_recording,
            rename_speaker,
            save_notes,
            list_templates,
            set_template,
            set_action_done,
            ask_recording,
            audio_path,
            get_settings,
            set_settings,
            set_auto_record,
            start_capture,
            pause_capture,
            resume_capture,
            stop_capture,
            capture_status,
            poll_meetings,
            ollama_status,
            pull_model,
            pull_progress,
            download_models,
            detected_tier,
        ])
        .run(tauri::generate_context!())
        .expect("error while running tauri application");
}
